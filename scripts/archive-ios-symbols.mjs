import {execFileSync} from 'node:child_process';
import {cp,mkdir,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..'),mode=process.argv[2]||'Debug';
if(!['Debug','Release'].includes(mode))throw Error('用法：node scripts/archive-ios-symbols.mjs Debug|Release');
const product=resolve(root,`ios/build/Build/Products/${mode}-iphoneos`),symbols=resolve(product,'EnglishPrinter.app.dSYM');
const output=execFileSync('xcrun',['dwarfdump','--uuid',symbols],{encoding:'utf8'});
const ids=[...output.matchAll(/UUID: ([A-F0-9-]+) \(([^)]+)\)/gi)].map(m=>({uuid:m[1],arch:m[2]}));
if(!ids.length)throw Error('没有找到构建符号，请先构建对应版本。');
const destination=resolve(root,'.local/diagnostics/symbols',ids[0].uuid);
await mkdir(destination,{recursive:true,mode:0o700});await cp(symbols,resolve(destination,'EnglishPrinter.app.dSYM'),{recursive:true});
await writeFile(resolve(destination,'build.json'),JSON.stringify({mode,builtAt:new Date().toISOString(),ids},null,2),{mode:0o600});
console.log('崩溃符号已保留：'+destination);
